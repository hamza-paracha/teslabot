CREATE TABLE records (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE oauth_states (hash TEXT PRIMARY KEY, browser_hash TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE sessions (hash TEXT PRIMARY KEY, expires INTEGER NOT NULL);
CREATE TABLE locks (name TEXT PRIMARY KEY, owner TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE usage (month TEXT NOT NULL, day TEXT NOT NULL, category TEXT NOT NULL, count INTEGER NOT NULL DEFAULT 0, estimated_usd REAL NOT NULL DEFAULT 0, PRIMARY KEY(day,category));
CREATE TABLE audit (id INTEGER PRIMARY KEY AUTOINCREMENT, event TEXT NOT NULL, created INTEGER NOT NULL);
CREATE INDEX audit_created ON audit(created);
